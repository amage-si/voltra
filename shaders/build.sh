#!/bin/sh
# Rebuilds the SPIR-V shaders and their Bend embedding, reproducibly.
# Requires glslc (shaderc) and spirv-val (SPIRV-Tools). Run from anywhere:
#   sh shaders/build.sh
set -eu
cd "$(dirname "$0")"

for stage in vert frag; do
  glslc --target-env=vulkan1.3 -O -o "quad.$stage.spv" "quad.$stage"
  spirv-val --target-env vulkan1.3 "quad.$stage.spv"
done

# Bend has no binary include, so the words are emitted as list literals.
words() {
  od -An -v -t u4 "$1" | tr -s ' \n' ' ' | sed 's/^ //; s/ $//; s/ /, /g' |
    fold -s -w 76 | sed 's/^/    /; s/ *$//'
}

{
  echo "import Base"
  echo
  echo "# Generated by shaders/build.sh from quad.vert and quad.frag."
  echo "# Do not edit by hand; edit the GLSL and rerun the script."
  echo
  echo "def quad_vert() -> List<&2, U32>:"
  echo "  ["
  words quad.vert.spv
  echo "  ]"
  echo
  echo "def quad_frag() -> List<&2, U32>:"
  echo "  ["
  words quad.frag.spv
  echo "  ]"
} > spirv.bend
echo "wrote shaders/spirv.bend"
